#!/bin/bash
#
# check_api_key.sh — fail the build clearly when the Osho API key is missing.
#
# Copyright (c) 2026 Sandalbar Enterprises, Inc.
# This file is part of Rajneesh Discourse, a fork of VLC for iOS (GPLv2+/GPLv3).
#
# The discourse API requires an `x-api-key` header on every request. The key is
# a secret and must never be committed. Supply it in one of these ways (all
# gitignored):
#
#   1. A `.env` file at the repo root:
#          OSHO_API_KEY=your-key-here
#   2. A `Secrets.xcconfig` at the repo root:
#          API_KEY = your-key-here
#   3. The `OSHO_API_KEY` environment variable (CI / xcodebuild).
#
# This script is wired into the `VLC-iOS` / `VLC-iOS-no-watch` targets as a
# "Run Script" build phase so a missing key fails early with an actionable
# message instead of shipping a broken binary.
#
# Output: it writes `GeneratedSecrets.xcconfig` into the build's derived sources
# and appends the resolved values to the target's xcconfig via the
# `API_KEY` / `API_BASE_URL` build settings consumed by Info.plist.

set -euo pipefail

REPO_ROOT="${SRCROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)}"
cd "$REPO_ROOT"

API_BASE_URL_DEFAULT="https://oshoapi-0i8tq.bunny.run/"

api_key="${OSHO_API_KEY:-${API_KEY:-}}"

# 0. The project convention: a gitignored `.env.production` at the repo root.
if [[ -z "${api_key}" && -f ".env.production" ]]; then
    api_key="$(grep -E '^[[:space:]]*(OSHO_)?API_KEY[[:space:]]*=' .env.production 2>/dev/null | tail -n1 | sed -E 's/^[[:space:]]*(OSHO_)?API_KEY[[:space:]]*=[[:space:]]*//' | tr -d '"'"'"' \r' || true)"
fi

# 1. .env file
if [[ -z "${api_key}" && -f ".env" ]]; then
    api_key="$(grep -E '^[[:space:]]*(OSHO_)?API_KEY[[:space:]]*=' .env 2>/dev/null | tail -n1 | sed -E 's/^[[:space:]]*(OSHO_)?API_KEY[[:space:]]*=[[:space:]]*//' | tr -d '"'"'"' \r' || true)"
fi

# 2. Secrets.xcconfig file
if [[ -z "${api_key}" && -f "Secrets.xcconfig" ]]; then
    api_key="$(grep -E '^[[:space:]]*API_KEY[[:space:]]*=' Secrets.xcconfig 2>/dev/null | tail -n1 | sed -E 's/^[[:space:]]*API_KEY[[:space:]]*=[[:space:]]*//' | tr -d ' \r' || true)"
fi

if [[ -z "${api_key}" ]]; then
    echo "error: Osho API key is missing." >&2
    echo "error: Rajneesh Discourse needs an x-api-key to talk to the discourse API." >&2
    echo "error: Provide it in one of these (gitignored) locations:" >&2
    echo "error:   1. .env.production -> API_KEY=your-key-here   (project convention)" >&2
    echo "error:   2. .env            -> OSHO_API_KEY=your-key-here" >&2
    echo "error:   3. Secrets.xcconfig -> API_KEY = your-key-here" >&2
    echo "error:   4. environment      -> export OSHO_API_KEY=your-key-here" >&2
    echo "error: Never commit the key. See AGENTS.md section 3.4." >&2
    exit 1
fi

api_base_url="${OSHO_API_URL:-$API_BASE_URL_DEFAULT}"

# Emit a generated header with the values. The key is compiled in as a constant,
# never checked into source control. The header is written to the shared derived
# sources directory so the app target, the test targets and their dependency
# scans all find it (`SHARED_DERIVED_FILE_DIR` is identical for every target of
# the same configuration/platform).
out_dir="${SHARED_DERIVED_FILE_DIR:-${DERIVED_FILE_DIR:-${BUILT_PRODUCTS_DIR:-.}}}"
out_file="${out_dir}/DiscourseSecrets.h"
mkdir -p "$out_dir"
cat > "$out_file" <<EOF
// Generated by Buildsystem/scripts/check_api_key.sh — do not commit.
// Copyright (c) 2026 Sandalbar Enterprises, Inc.
#define RD_API_KEY @"${api_key}"
#define RD_API_BASE_URL @"${api_base_url}"
EOF

echo "note: Wrote discourse API configuration to ${out_file}"
